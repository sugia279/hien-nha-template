export function translate(text: string, language: 'vi' | 'en'): string {
  if (language === 'vi') {
    for (const [source, value] of Object.entries(vietnameseErrors).sort(
      (a, b) => b[0].length - a[0].length,
    ))
      text = text.replaceAll(source, value);
    return text;
  }
  const normalized = text.replace(/\s+/g, ' ').trim();
  if (english[normalized])
    return (
      (text.match(/^\s*/)?.[0] || '') +
      english[normalized] +
      (text.match(/\s*$/)?.[0] || '')
    );
  for (const [source, value] of entries) text = text.replaceAll(source, value);
  return text;
}
export const t = (text: string) => translate(text, locale);
const dynamic = new Map<Text, string>();
export function uiText(target: HTMLElement, source: string) {
  target.textContent = t(source);
  if (target.firstChild) dynamic.set(target.firstChild as Text, source);
  if (dynamic.size > 512)
    for (const node of dynamic.keys())
      if (!node.isConnected) dynamic.delete(node);
}
export function initializeLanguage() {
  const records: { node: Text; source: string }[] = [],
    attributes: { element: Element; name: string; source: string }[] = [];
  const walker = document.createTreeWalker(
    document.documentElement,
    NodeFilter.SHOW_TEXT,
  );
  let node: Node | null;
  while ((node = walker.nextNode()))
    if (
      node.textContent?.trim() &&
      !node.parentElement?.closest(
        'script,style,input,textarea,[data-owner-text]',
      )
    )
      records.push({ node: node as Text, source: node.textContent });
  for (const element of document.querySelectorAll('[aria-label],[title]'))
    for (const name of ['aria-label', 'title'])
      if (element.hasAttribute(name))
        attributes.push({ element, name, source: element.getAttribute(name)! });
  document
    .getElementById('studio-language')!
    .addEventListener('change', (event) => {
      locale = (event.target as HTMLSelectElement).value as 'vi' | 'en';
      document.documentElement.lang = locale;
      for (const { node, source } of records)
        if (node.isConnected) node.nodeValue = t(source);
      for (const { element, name, source } of attributes)
        element.setAttribute(name, t(source));
      for (const [node, source] of dynamic)
        if (node.isConnected) node.nodeValue = t(source);
        else dynamic.delete(node);
      window.dispatchEvent(new Event('hien-nha-language'));
    });
}
